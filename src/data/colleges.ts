export function getCoordinates(locationName: string): RouteCoord {
  if (LOCATION_COORDINATES[locationName]) {
    return LOCATION_COORDINATES[locationName];
  }
  // Case-insensitive key lookup fallback
  const searchKey = locationName.toLowerCase().trim();
  const matchedKey = Object.keys(LOCATION_COORDINATES).find(
    k => k.toLowerCase().trim() === searchKey
  );
  if (matchedKey) {
    return LOCATION_COORDINATES[matchedKey];
  }
  // Fallback to average coordinate in Mangalore if not found
  return { name: locationName, lat: 12.8700, lng: 74.8400 };
}

// Haversine formula to compute distance in km
export function calculateDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // radius of Earth in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const d = R * c;
  return parseFloat(d.toFixed(1));
}

// Standard average motorcycle/cab travel speed in cities is ~35 km/h
export function calculateTravelTimeMinutes(distanceKm: number): number {
  const avgSpeedKmh = 35;
  const timeHours = distanceKm / avgSpeedKmh;
  const minutes = Math.ceil(timeHours * 60) + 5; // adding 5 mins margin
  return minutes;
}
